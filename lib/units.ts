// "EA" -> "Each". Unknown codes are left as printed.
export function unitName(code: string) {
  const name = names[code.toUpperCase()];
  if (!name) return code;
  return name.charAt(0) + name.slice(1).toLowerCase();
}
export const isUnitCode = (code: string) => code.toUpperCase() in names;
